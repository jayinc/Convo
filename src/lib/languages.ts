export function languageName(codeOrName: string): string {
  const l = LANGUAGES.find(
    (x) =>
      x.code === codeOrName ||
      x.name.toLowerCase() === codeOrName.toLowerCase(),
  );
  return l?.name ?? codeOrName;
}
